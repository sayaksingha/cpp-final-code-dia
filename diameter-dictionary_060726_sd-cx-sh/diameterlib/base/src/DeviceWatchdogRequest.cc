BOOLEAN DeviceWatchdogRequest::isPresent(int tag){
	return (mTagsPresent[tag])?true:false;
}

DeviceWatchdogRequest::DeviceWatchdogRequest()
{
	mOriginHost = NULL;
	mOriginRealm = NULL;
	mOriginStateId = NULL;
	mCCRequestType = NULL;
	mTagsPresent.reset();
	mMandatoryAvpCheckVal= bitset<4>(string("1111"));
	mMandatoryAvpSetVal.reset();
}

DeviceWatchdogRequest::~DeviceWatchdogRequest()
{
	if(mOriginHost != NULL)
		delete mOriginHost;
	if(mOriginRealm != NULL)
		delete mOriginRealm;
	if(mOriginStateId != NULL)
		delete mOriginStateId;
	if(mCCRequestType != NULL)
		delete mCCRequestType;
}

